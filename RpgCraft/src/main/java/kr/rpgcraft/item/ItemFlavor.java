    /** 등록된 원형에 칭호/문구를 입힌다 (여러 번 호출해도 안전) */
    public static void apply(ItemRegistry reg) {
        for (Map.Entry<String, F> e : MAP.entrySet()) {
            ItemTemplate t = reg.get(e.getKey());
            if (t == null) continue;
            t.epithet = e.getValue().epithet();
            t.flavor = new java.util.ArrayList<>(java.util.Arrays.asList(e.getValue().lines()));
        }
    }
